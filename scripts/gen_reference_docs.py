def roles_of(route: APIRoute):
    found = None

    def walk(dep):
        nonlocal found
        if getattr(dep.call, "allowed_roles", None):
            found = dep.call.allowed_roles
        for d in dep.dependencies:
            walk(d)
    walk(route.dependant)
    return found


def access_matrix():
    rows = []

    def all_routes():
        # this FastAPI keeps included routers nested (_IncludedRouter), so walk into them
        for r in app.routes:
            if hasattr(r, "original_router"):
                yield from (x for x in r.original_router.routes if isinstance(x, APIRoute))
            elif isinstance(r, APIRoute):
                yield r
    for r in all_routes():
        if not (r.path.startswith("/api") or r.path == "/health"):
            continue
        roles = roles_of(r)
        for method in sorted(r.methods):
            cells = ["public" if roles is None else ("yes" if role in roles else "403") for role in
                     ("CUSTOMER", "COORDINATOR", "TRANSPORTER")]
            rows.append((r.path, method, cells, OWNERSHIP.get(r.path, "-" if roles is None or "COORDINATOR" in roles else "")))
    rows.sort()
    out = ["# API access matrix", "",
           "Generated by `scripts/gen_reference_docs.py` from the route dependencies. Do not edit by hand.",
           "Tested by one parameterised test: `backend/tests/test_access.py::test_role_endpoint_matrix`.",
           "", "Anonymous calls to any non-public endpoint return 401. A wrong role returns 403. "
           "Another user's resource returns 404 (it never reveals that the resource exists).", "",
           "| Method | Endpoint | Customer | Coordinator | Transporter | Ownership rule |",
           "| --- | --- | --- | --- | --- | --- |"]
    for path, method, cells, own in rows:
        out.append(f"| {method} | `{path}` | {' | '.join(cells)} | {own} |")
    (ROOT / "docs" / "API_ACCESS_MATRIX.md").write_text("\n".join(out) + "\n", encoding="utf-8")


def db_reference():
    out = ["# Database reference", "",
           "Generated by `scripts/gen_reference_docs.py` from `backend/app/models.py`. Do not edit by hand.",
           "SQLite, WAL mode, `PRAGMA foreign_keys=ON` on every connection, busy timeout 5000 ms. "
           "Timestamps are UTC (displayed in Asia/Kolkata).", ""]
    for t in Base.metadata.sorted_tables:
        out += [f"## `{t.name}`", "", "| Column | Type | Null | Key |", "| --- | --- | --- | --- |"]
        for c in t.columns:
            key = "PK" if c.primary_key else ", ".join(f"FK -> {fk.target_fullname}" for fk in c.foreign_keys)
            out.append(f"| {c.name} | {c.type} | {'yes' if c.nullable else 'no'} | {key} |")
        cons = [c for c in t.constraints if isinstance(c, (CheckConstraint, UniqueConstraint))]
        if cons:
            out.append("")
            for c in cons:
                if isinstance(c, CheckConstraint):
                    out.append(f"- CHECK `{c.sqltext}`")
                else:
                    out.append(f"- UNIQUE ({', '.join(col.name for col in c.columns)})")
        out.append("")
    (ROOT / "docs" / "DB_REFERENCE.md").write_text("\n".join(out), encoding="utf-8")


